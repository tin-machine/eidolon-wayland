"""Frozen B1 vectors, shared by Python/Rust and future Kotlin. No app mocks.

The expected bytes/digests are literal fixture data, never generated by the
implementation under test. Synthetic evidence does not prove a live owner.
"""
import copy
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import unittest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
import linux_desktop_v3_contract as C
import linux_desktop_v3_presentation as P

FIXTURE_PATH = Path(__file__).parent / "fixtures/linux-desktop-v3-contract.json"
FIXTURE = json.loads(FIXTURE_PATH.read_bytes())
RECORDS = {v["id"]: v for v in FIXTURE["records"]}


def source(name):
    return RECORDS[name]["raw"].encode()


def encoded(v):
    return json.dumps(v).encode()


def parsed(kind, raw):
    classes = {"pins": C.Pins, "manifest": C.Manifest, "context": C.Context, "storage": C.StorageRecord,
               "capture": C.StorageCapture, "owner": C.StorageOwner, "selection": C.Selection, "origin": P.NativeOrigin,
               "observation": P.Observation}
    if kind in classes:
        return classes[kind].parse(raw).record()
    if kind == "bootstrap":
        return list(C.Bootstrap.parse(raw).vector())
    if kind == "catalog":
        return C.validate_catalog(raw, C.Context.parse(source("context")), C.Pins.parse(source("pins")))
    if kind.startswith("reason_"):
        return C.parse_reason(raw, kind.removeprefix("reason_")).value
    v = C.parse_json(raw)
    if kind == "parent":
        P.validate_parent(v)
    elif kind == "target":
        P.validate_target(v)
    else:
        assert kind == "json"
    return v


class GoldenTests(unittest.TestCase):
    def setUp(self):
        self.pins = C.Pins.parse(source("pins"))
        self.context = C.Context.parse(source("context"))
        self.storage = C.StorageRecord.parse(source("storage"))
        self.selection = C.Selection.parse(source("selection"))

    def test_fixed_canonical_bytes_and_digests_in_every_language(self):
        self.assertEqual(FIXTURE["purpose"], "synthetic-contract-only; never production pins or acceptance")
        self.assertEqual(len(RECORDS), len(FIXTURE["records"]))
        for case in FIXTURE["records"]:
            with self.subTest(vector=case["id"]):
                v = parsed(case["kind"], case["raw"].encode())
                data = C.canonical_json(v)
                self.assertEqual(data, case["canonical_utf8"].encode())
                self.assertEqual(hashlib.sha256(data).hexdigest(), case["sha256"])
                self.assertFalse(data.endswith(b"\n"))

    def test_hash_preimages_are_exact_and_do_not_contain_derived_hashes(self):
        manifest = C.Manifest.parse(source("manifest"))
        manifest.matches_pins(self.pins)
        self.assertEqual(self.pins.build_input(), json.loads(source("build_input")))
        self.assertEqual(self.pins.build_id(), RECORDS["build_input"]["sha256"])
        self.assertEqual(self.context.scope(), RECORDS["context"]["sha256"])
        self.assertEqual(C.catalog_revision_input(self.context, self.pins), json.loads(source("catalog_input")))
        self.assertEqual(C.catalog_revision(self.context, self.pins), RECORDS["catalog_input"]["sha256"])
        self.assertEqual(C.catalog_descriptor(self.context, self.pins), json.loads(source("catalog")))
        self.selection.matches(self.context, self.pins)

    def test_manifest_hash_mismatch_is_not_an_available_bundle(self):
        p = self.pins.record()
        p["app_manifest_sha256"] = "f" * 64
        with self.assertRaisesRegex(C.ContractError, "APP_DEPENDENCY_CHANGED"):
            C.Manifest.parse(source("manifest")).matches_pins(C.Pins.parse(encoded(p)))
        self.assertNotIn("available", C.catalog_descriptor(self.context, self.pins))

    def test_all_raw_negative_vectors_reject_before_canonicalization(self):
        ids = set()
        for case in FIXTURE["invalid"]:
            with self.subTest(vector=case["id"]):
                self.assertNotIn(case["id"], ids)
                ids.add(case["id"])
                data = bytes.fromhex(case["raw_hex"]) if "raw_hex" in case else case["raw"].encode()
                with self.assertRaises(C.ContractError) as raised:
                    parsed(case["kind"], data)
                if "error" in case:
                    self.assertEqual(str(raised.exception), case["error"])

    def test_stale_selection_storage_owner_origin_and_bootstrap_relations(self):
        for case in FIXTURE["relations"]:
            with self.subTest(vector=case["id"]), self.assertRaises(C.ContractError):
                data, kind = case["raw"].encode(), case["kind"]
                if kind == "selection_context":
                    self.selection.matches(C.Context.parse(data), self.pins)
                elif kind == "selection_pins":
                    self.selection.matches(self.context, C.Pins.parse(data))
                elif kind == "storage_capture":
                    self.storage.matches_capture(C.StorageCapture.parse(data))
                elif kind == "owner_context":
                    C.StorageOwner.parse(data).matches_context(self.context)
                elif kind == "bootstrap_context":
                    C.Bootstrap.parse(data).matches(self.context, self.pins)
                elif kind == "origin_context":
                    P.NativeOrigin.parse(data).matches(self.context, self.selection, self.pins)
                else:
                    self.fail("unknown fixture kind")

    def test_fixed_serve_and_recover_vectors(self):
        serve = C.Bootstrap("serve", self.context, self.pins)
        recover = C.Bootstrap("recover", self.context, self.pins, "11111111-2222-3333-4444-555555555555")
        self.assertEqual(list(serve.vector()), json.loads(source("serve")))
        self.assertEqual(list(recover.vector()), json.loads(source("recover")))
        self.assertEqual(len(serve.vector()), 14)
        self.assertEqual(len(recover.vector()), 15)
        for name in ("serve", "recover", "recover_unknown_boot"):
            C.Bootstrap.parse(source(name)).matches(self.context, self.pins)

    def test_no_remote_version_negotiation_or_v2_upgrade(self):
        self.assertIs(C.DecoderVersion.selected(self.pins, C.REVISION), C.DecoderVersion.V3)
        for revision in ("eidolon-linux-desktop-v2", "eidolon-linux-desktop-v4", None, True):
            with self.subTest(revision=revision), self.assertRaises(C.ContractError):
                C.DecoderVersion.selected(self.pins, revision)

    def test_checked_constructors_cannot_bypass_typed_values(self):
        for cls in (C.Pins, C.Manifest, C.Context, C.StorageRecord, C.StorageCapture, C.StorageOwner, C.Selection, P.NativeOrigin, P.Observation):
            with self.subTest(cls=cls.__name__), self.assertRaises(C.ContractError):
                cls(b"{}")
        class EmptyCapture:
            def record(self):
                return {}
        with self.assertRaises(C.ContractError):
            self.storage.matches_capture(EmptyCapture())
        with self.assertRaises(C.ContractError):
            P.Startup(P.NativeOrigin.parse(source("origin")), 0, startup_completed=True)

    def test_storage_host_user_preimage_preserves_existing_profile_binding(self):
        profile = FIXTURE["profile"]
        values = ["eidolon-profile-v2", profile["installation"], profile["profile_id"], profile["revision"], profile["backend"],
                  profile["host"], str(profile["port"]), profile["username"], profile["host_key"]]
        self.assertEqual(hashlib.sha256("\0".join(values).encode()).hexdigest(), FIXTURE["profile_binding"])
        h = hashlib.sha256(profile["host_key"].encode()).hexdigest()
        self.assertEqual(C.host_user_input(h, profile["username"]), json.loads(source("host_user_input")))
        self.assertEqual(C.host_user_binding(h, profile["username"]), self.storage.record()["host_user_binding"])
        self.storage.matches_capture(C.StorageCapture.parse(source("capture")))
        self.storage.matches_context(self.context)
        C.StorageOwner.parse(source("owner")).matches_context(self.context)

    def test_storage_transition_requires_capture_cas_and_full_reclamation(self):
        for case in FIXTURE["storage_transitions"]:
            with self.subTest(vector=case["id"]):
                new = C.StorageRecord.parse(encoded(case["new"]))
                capture = C.StorageCapture.parse(encoded(case["capture"]))
                def apply():
                    return C.validate_storage_transition(self.storage, new, expected_old_sha256=case["expected_old_sha256"],
                        capture=capture, explicit_save=case["explicit_save"], fully_reclaimed=case["fully_reclaimed"])
                if case["expected_change"] is None:
                    with self.assertRaises(C.ContractError):
                        apply()
                else:
                    self.assertEqual(apply(), case["expected_change"])

    def test_runtime_inputs_are_copies_and_records_stay_immutable(self):
        view = self.pins.record()
        view["schema"] = 99
        self.assertEqual(self.pins.record()["schema"], 2)
        with self.assertRaises(AttributeError):
            self.pins._bytes = b"{}"
        self.assertNotEqual(C.StorageInstallationId("a" * 32), C.ProfileStorageId("a" * 32))

    def test_record_size_boundaries_are_bytes(self):
        for cls, name, limit in ((C.Pins, "pins", 4096), (C.Manifest, "manifest", 16384), (C.Context, "context", 16384)):
            raw = source(name)
            with self.subTest(name=name):
                self.assertEqual(cls.parse(raw + b" " * (limit - len(raw))), cls.parse(raw))
                with self.assertRaises(C.ContractError):
                    cls.parse(raw + b" " * (limit + 1 - len(raw)))

    def test_import_and_parse_do_not_launch_create_profile_or_change_environment(self):
        code = """
import os, pathlib, socket, subprocess, sys
from unittest.mock import patch
sys.path.insert(0, sys.argv[1])
before = dict(os.environ)
def forbidden(*a, **kw): raise AssertionError('unexpected I/O')
with patch.object(os, 'open', forbidden), patch.object(os, 'mkdir', forbidden), patch.object(os, 'makedirs', forbidden), patch.object(subprocess, 'Popen', forbidden), patch.object(socket, 'socket', forbidden):
    import linux_desktop_v3_contract as c
    import linux_desktop_v3_presentation as p
    assert c.canonical_json(c.parse_json(b'{"n":1}')) == b'{"n":1}'
assert dict(os.environ) == before
"""
        result = subprocess.run([sys.executable, "-B", "-c", code, str(ROOT / "scripts")], capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)


class PresentationGoldenTests(unittest.TestCase):
    def test_origin_matches_captured_context_and_selection(self):
        P.NativeOrigin.parse(source("origin")).matches(C.Context.parse(source("context")), C.Selection.parse(source("selection")), C.Pins.parse(source("pins")))

    def test_fixed_sequences_and_rejected_evidence(self):
        ids = set()
        for case in FIXTURE["presentation"]:
            self.assertNotIn(case["id"], ids)
            ids.add(case["id"])
            origin = P.NativeOrigin.parse(encoded(case["origin"])) if "origin" in case else P.NativeOrigin.parse(source("origin"))
            state = P.Startup.begin(origin, case["t0_ms"], tuple(case["before"]))
            for index, step in enumerate(case["steps"]):
                with self.subTest(vector=case["id"], step=index):
                    old = state.summary()
                    if step.get("error") == "parse":
                        with self.assertRaises(C.ContractError):
                            P.Observation.parse(encoded(step["observation"]))
                    elif "error" in step:
                        observation = P.Observation.parse(encoded(step["observation"]))
                        with self.assertRaisesRegex(C.ContractError, step["error"]):
                            state.advance(observation)
                    else:
                        state = state.advance(P.Observation.parse(encoded(step["observation"])))
                        self.assertEqual(state.summary(), step["expected"])
                    if "error" in step:
                        self.assertEqual(state.summary(), old)


